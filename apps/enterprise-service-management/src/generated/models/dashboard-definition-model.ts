import type { Person } from './person-model';
import type { Workspace } from './workspace-model';

export const DashboardDefinitionSharingScopeKeyToLabel = {
  'Private': 'Private',
  'Workspace': 'Workspace',
  'Service': 'Service'
} as const;
export type DashboardDefinitionSharingScopeKey = keyof typeof DashboardDefinitionSharingScopeKeyToLabel;

export const DashboardDefinitionStatusKeyToLabel = {
  'Active': 'Active',
  'Archived': 'Archived'
} as const;
export type DashboardDefinitionStatusKey = keyof typeof DashboardDefinitionStatusKeyToLabel;

export interface DashboardDefinition {
  /**
   * @displayName Dashboard Definition ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  name1: string;
  /**
   * @displayName Created At
   * @validationRule Required for create/update operations
   */
  createdAt: string;
  /**
   * @displayName Is Deleted
   * @validationRule Required for create/update operations
   */
  isDeleted: boolean;
  /**
   * @displayName Layout JSON
   * @validationRule Required for create/update operations
   */
  layoutJSON: string;
  /**
   * @displayName Owner Person
   * @validationRule Required for create/update operations
   */
  ownerPerson: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Sharing Scope
   * @validationRule Required for create/update operations
   */
  sharingScopeKey: DashboardDefinitionSharingScopeKey;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: DashboardDefinitionStatusKey;
  /**
   * @displayName Updated At
   * @validationRule Required for create/update operations
   */
  updatedAt: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _DashboardDefinition = 'DashboardDefinition' as const;