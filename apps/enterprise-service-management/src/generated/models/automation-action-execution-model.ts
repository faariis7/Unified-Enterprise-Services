import type { AutomationAction } from './automation-action-model';
import type { AutomationExecution } from './automation-execution-model';
import type { Request } from './request-model';
import type { Workspace } from './workspace-model';

export const AutomationActionExecutionStatusKeyToLabel = {
  'Succeeded': 'Succeeded',
  'Failed': 'Failed',
  'Skipped': 'Skipped',
  'Blocked': 'Blocked'
} as const;
export type AutomationActionExecutionStatusKey = keyof typeof AutomationActionExecutionStatusKeyToLabel;

export interface AutomationActionExecution {
  /**
   * @displayName Automation Action Execution ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Idempotency Key
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  idempotencyKey: string;
  /**
   * @displayName Automation Action
   */
  automationAction?: Pick<AutomationAction, 'id' | 'actionName'>;
  /**
   * @displayName Automation Execution
   * @validationRule Required for create/update operations
   */
  automationExecution: Pick<AutomationExecution, 'id' | 'correlationKey'>;
  /**
   * @displayName Details
   * @validationRule Required for create/update operations
   */
  details: string;
  /**
   * @displayName Executed At
   * @validationRule Required for create/update operations
   */
  executedAt: string;
  /**
   * @displayName Request
   * @validationRule Required for create/update operations
   */
  request: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: AutomationActionExecutionStatusKey;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _AutomationActionExecution = 'AutomationActionExecution' as const;