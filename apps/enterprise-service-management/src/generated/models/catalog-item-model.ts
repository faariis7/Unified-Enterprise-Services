import type { FormDefinition } from './form-definition-model';
import type { Service } from './service-model';
import type { Workspace } from './workspace-model';

export const CatalogItemDefaultPriorityKeyToLabel = {
  'Low': 'Low',
  'Medium': 'Medium',
  'High': 'High',
  'Critical': 'Critical'
} as const;
export type CatalogItemDefaultPriorityKey = keyof typeof CatalogItemDefaultPriorityKeyToLabel;

export const CatalogItemStatusKeyToLabel = {
  'Draft': 'Draft',
  'Published': 'Published',
  'Retired': 'Retired'
} as const;
export type CatalogItemStatusKey = keyof typeof CatalogItemStatusKeyToLabel;

export interface CatalogItem {
  /**
   * @displayName Catalog Item ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Item Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  itemName: string;
  /**
   * @displayName Approval Required
   * @validationRule Required for create/update operations
   */
  approvalRequired: boolean;
  /**
   * @displayName Default Priority
   * @validationRule Required for create/update operations
   */
  defaultPriorityKey: CatalogItemDefaultPriorityKey;
  /**
   * @displayName Form Definition
   * @validationRule Required for create/update operations
   */
  formDefinition: Pick<FormDefinition, 'id' | 'name1'>;
  /**
   * @displayName Initial Task Title
   */
  initialTaskTitle?: string;
  /**
   * @displayName Item Code
   * @validationRule Required for create/update operations
   */
  itemCode: string;
  /**
   * @displayName Requester Eligible
   * @validationRule Required for create/update operations
   */
  requesterEligible: boolean;
  /**
   * @displayName Request Type Code
   * @validationRule Required for create/update operations
   */
  requestTypeCode: string;
  /**
   * @displayName Service
   * @validationRule Required for create/update operations
   */
  service: Pick<Service, 'id' | 'serviceName'>;
  /**
   * @displayName Service Target Hours
   * @validationRule Required for create/update operations
   */
  serviceTargetHours: number;
  /**
   * @displayName Short Description
   * @validationRule Required for create/update operations
   */
  shortDescription: string;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: CatalogItemStatusKey;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _CatalogItem = 'CatalogItem' as const;