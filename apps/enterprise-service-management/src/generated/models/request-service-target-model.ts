import type { Request } from './request-model';
import type { ServiceTargetPolicy } from './service-target-policy-model';
import type { ServiceTargetRule } from './service-target-rule-model';
import type { Workspace } from './workspace-model';

export const RequestServiceTargetStatusKeyToLabel = {
  'Active': 'Active',
  'Warning': 'Warning',
  'Paused': 'Paused',
  'Met': 'Met',
  'Breached': 'Breached',
  'Cancelled': 'Cancelled'
} as const;
export type RequestServiceTargetStatusKey = keyof typeof RequestServiceTargetStatusKeyToLabel;

export const RequestServiceTargetTargetTypeKeyToLabel = {
  'Response': 'Response',
  'Resolution': 'Resolution',
  'Fulfillment': 'Fulfillment',
  'Approval': 'Approval',
  'Custom': 'Custom'
} as const;
export type RequestServiceTargetTargetTypeKey = keyof typeof RequestServiceTargetTargetTypeKeyToLabel;

export interface RequestServiceTarget {
  /**
   * @displayName Request Service Target ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Snapshot Policy Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  snapshotPolicyName: string;
  /**
   * @displayName Accumulated Paused Minutes
   * @validationRule Required for create/update operations
   */
  accumulatedPausedMinutes: number;
  /**
   * @displayName Due At
   * @validationRule Required for create/update operations
   */
  dueAt: string;
  /**
   * @displayName Last Evaluated At
   * @validationRule Required for create/update operations
   */
  lastEvaluatedAt: string;
  /**
   * @displayName Remaining Minutes
   * @validationRule Required for create/update operations
   */
  remainingMinutes: number;
  /**
   * @displayName Request
   * @validationRule Required for create/update operations
   */
  requestId: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName Service Target Policy
   * @validationRule Required for create/update operations
   */
  serviceTargetDefinition: Pick<ServiceTargetPolicy, 'id' | 'name1'>;
  /**
   * @displayName Service Target Rule
   * @validationRule Required for create/update operations
   */
  serviceTargetRule: Pick<ServiceTargetRule, 'id' | 'ruleName'>;
  /**
   * @displayName Snapshot Duration Minutes
   * @validationRule Required for create/update operations
   */
  snapshotDurationMinutes: number;
  /**
   * @displayName Started At
   * @validationRule Required for create/update operations
   */
  startedAt: string;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: RequestServiceTargetStatusKey;
  /**
   * @displayName Snapshot Target Type
   * @validationRule Required for create/update operations
   */
  targetTypeKey: RequestServiceTargetTargetTypeKey;
  /**
   * @displayName Warning At
   * @validationRule Required for create/update operations
   */
  warningAt: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspaceId: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _RequestServiceTarget = 'RequestServiceTarget' as const;