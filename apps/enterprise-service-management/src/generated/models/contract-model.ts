import type { Person } from './person-model';
import type { Vendor } from './vendor-model';
import type { Workspace } from './workspace-model';

export const ContractAgreementModeKeyToLabel = {
  'FixedTerm': 'Fixed Term',
  'AutoRenewing': 'Auto Renewing'
} as const;
export type ContractAgreementModeKey = keyof typeof ContractAgreementModeKeyToLabel;

export const ContractContractTypeKeyToLabel = {
  'Service': 'Service',
  'Purchase': 'Purchase',
  'Subscription': 'Subscription',
  'Lease': 'Lease',
  'Maintenance': 'Maintenance',
  'Other': 'Other'
} as const;
export type ContractContractTypeKey = keyof typeof ContractContractTypeKeyToLabel;

export const ContractLifecycleStatusKeyToLabel = {
  'Draft': 'Draft',
  'Active': 'Active',
  'Expiring': 'Expiring',
  'Expired': 'Expired',
  'Terminated': 'Terminated',
  'Archived': 'Archived'
} as const;
export type ContractLifecycleStatusKey = keyof typeof ContractLifecycleStatusKeyToLabel;

export interface Contract {
  /**
   * @displayName Contract ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Title
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  title: string;
  /**
   * @displayName Agreement Mode
   * @validationRule Required for create/update operations
   */
  agreementModeKey: ContractAgreementModeKey;
  /**
   * @displayName Contract Number
   * @validationRule Required for create/update operations
   */
  contractNumber: string;
  /**
   * @displayName Contract Type
   * @validationRule Required for create/update operations
   */
  contractTypeKey: ContractContractTypeKey;
  /**
   * @displayName Currency
   * @validationRule Required for create/update operations
   */
  currency: string;
  /**
   * @displayName Description
   * @validationRule Required for create/update operations
   */
  description: string;
  /**
   * @displayName End Date
   * @validationRule Required for create/update operations
   */
  endDate: string;
  /**
   * @displayName Lifecycle Status
   * @validationRule Required for create/update operations
   */
  lifecycleStatusKey: ContractLifecycleStatusKey;
  /**
   * @displayName Renewal, Termination, and Audit Details
   * @validationRule Required for create/update operations
   */
  renewalTerminationAndAuditDetails: string;
  /**
   * @displayName Responsible Person
   * @validationRule Required for create/update operations
   */
  responsiblePerson: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Start Date
   * @validationRule Required for create/update operations
   */
  startDate: string;
  /**
   * @displayName Total Value
   * @validationRule Required for create/update operations
   */
  totalValue: number;
  /**
   * @displayName Vendor
   * @validationRule Required for create/update operations
   */
  vendor: Pick<Vendor, 'id' | 'vendorName'>;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _Contract = 'Contract' as const;