import type { Person } from './person-model';

export const MetadataRecordEntityTypeKeyToLabel = {
  'ServiceCategory': 'Service Category',
  'Service': 'Service',
  'FormDefinition': 'Form Definition',
  'FormVersion': 'Form Version',
  'FormSection': 'Form Section',
  'FieldDefinition': 'Field Definition',
  'FieldOption': 'Field Option',
  'ValidationRule': 'Validation Rule',
  'VisibilityRule': 'Visibility Rule',
  'Request': 'Request',
  'RequestFieldValue': 'Request Field Value',
  'RequestAttachment': 'Request Attachment',
  'StatusDefinition': 'Status Definition',
  'RequestAuditEvent': 'Request Audit Event'
} as const;
export type MetadataRecordEntityTypeKey = keyof typeof MetadataRecordEntityTypeKeyToLabel;

export interface MetadataRecord {
  /**
   * @displayName Metadata Record ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Record Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  recordName: string;
  /**
   * @displayName Active
   * @validationRule Required for create/update operations
   */
  active: boolean;
  /**
   * @displayName Configuration JSON
   * @validationRule Required for create/update operations
   */
  configurationJSON: string;
  /**
   * @displayName Configuration Key
   * @validationRule Required for create/update operations
   */
  configurationKey: string;
  /**
   * @displayName Created At
   * @validationRule Required for create/update operations
   */
  createdAt: string;
  /**
   * @displayName Created By
   * @validationRule Required for create/update operations
   */
  createdBy: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Deleted At
   */
  deletedAt?: string;
  /**
   * @displayName Deleted By
   */
  deletedBy?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Entity Record ID
   * @validationRule Required for create/update operations
   */
  entityRecordID: string;
  /**
   * @displayName Entity Type
   * @validationRule Required for create/update operations
   */
  entityTypeKey: MetadataRecordEntityTypeKey;
  /**
   * @displayName Is Deleted
   * @validationRule Required for create/update operations
   */
  isDeleted: boolean;
  /**
   * @displayName Sort Order
   * @validationRule Required for create/update operations
   */
  sortOrder: number;
  /**
   * @displayName Updated At
   * @validationRule Required for create/update operations
   */
  updatedAt: string;
  /**
   * @displayName Updated By
   * @validationRule Required for create/update operations
   */
  updatedBy: Pick<Person, 'id' | 'displayName'>;
}

export const _MetadataRecord = 'MetadataRecord' as const;