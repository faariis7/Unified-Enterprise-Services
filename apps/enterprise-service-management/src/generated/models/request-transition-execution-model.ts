import type { Person } from './person-model';
import type { StatusTransition } from './status-transition-model';
import type { Request } from './request-model';
import type { Workspace } from './workspace-model';

export const RequestTransitionExecutionStatusKeyToLabel = {
  'Succeeded': 'Succeeded',
  'Failed': 'Failed',
  'Blocked': 'Blocked'
} as const;
export type RequestTransitionExecutionStatusKey = keyof typeof RequestTransitionExecutionStatusKeyToLabel;

export interface RequestTransitionExecution {
  /**
   * @displayName Request Transition Execution ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Execution Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  executionName: string;
  /**
   * @displayName Actor
   * @validationRule Required for create/update operations
   */
  actor: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Comment
   */
  comment?: string;
  /**
   * @displayName Executed At
   * @validationRule Required for create/update operations
   */
  executedAt: string;
  /**
   * @displayName Failure Reason
   */
  failureReason?: string;
  /**
   * @displayName Lifecycle Transition
   * @validationRule Required for create/update operations
   */
  lifecycleTransition: Pick<StatusTransition, 'id' | 'transitionName'>;
  /**
   * @displayName Request
   * @validationRule Required for create/update operations
   */
  request: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName Source
   * @validationRule Required for create/update operations
   */
  source: string;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: RequestTransitionExecutionStatusKey;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _RequestTransitionExecution = 'RequestTransitionExecution' as const;