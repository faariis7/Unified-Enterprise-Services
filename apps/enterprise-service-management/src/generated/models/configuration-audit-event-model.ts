import type { Person } from './person-model';
import type { Workspace } from './workspace-model';

export const ConfigurationAuditEventActionKeyToLabel = {
  'Created': 'Created',
  'Updated': 'Updated',
  'OverrideSet': 'Override Set',
  'OverrideReset': 'Override Reset'
} as const;
export type ConfigurationAuditEventActionKey = keyof typeof ConfigurationAuditEventActionKeyToLabel;

export const ConfigurationAuditEventScopeKeyToLabel = {
  'Global': 'Global',
  'Workspace': 'Workspace',
  'Service': 'Service',
  'CatalogItem': 'Catalog Item'
} as const;
export type ConfigurationAuditEventScopeKey = keyof typeof ConfigurationAuditEventScopeKeyToLabel;

export const ConfigurationAuditEventSourceKeyToLabel = {
  'GlobalDefault': 'Global Default',
  'WorkspaceOverride': 'Workspace Override',
  'ServiceOverride': 'Service Override',
  'CatalogItemOverride': 'Catalog Item Override',
  'RequestCalculated': 'Request Calculated'
} as const;
export type ConfigurationAuditEventSourceKey = keyof typeof ConfigurationAuditEventSourceKeyToLabel;

export interface ConfigurationAuditEvent {
  /**
   * @displayName Configuration Audit Event ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Configuration Audit Event Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  configurationAuditEventName: string;
  /**
   * @displayName Action
   * @validationRule Required for create/update operations
   */
  actionKey: ConfigurationAuditEventActionKey;
  /**
   * @displayName Actor
   * @validationRule Required for create/update operations
   */
  actor: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName New Value
   */
  newValue?: string;
  /**
   * @displayName Occurred At
   * @validationRule Required for create/update operations
   */
  occurredAt: string;
  /**
   * @displayName Previous Value
   */
  previousValue?: string;
  /**
   * @displayName Scope
   * @validationRule Required for create/update operations
   */
  scopeKey: ConfigurationAuditEventScopeKey;
  /**
   * @displayName Setting Key
   * @validationRule Required for create/update operations
   */
  settingKey: string;
  /**
   * @displayName Source
   * @validationRule Required for create/update operations
   */
  sourceKey: ConfigurationAuditEventSourceKey;
  /**
   * @displayName Target Record ID
   * @validationRule Required for create/update operations
   */
  targetRecordID: string;
  /**
   * @displayName Workspace
   */
  workspace?: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _ConfigurationAuditEvent = 'ConfigurationAuditEvent' as const;