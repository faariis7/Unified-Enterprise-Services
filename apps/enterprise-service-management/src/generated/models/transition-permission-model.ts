import type { StatusTransition } from './status-transition-model';
import type { Workspace } from './workspace-model';

export const TransitionPermissionScopeKeyToLabel = {
  'Workspace': 'Workspace',
  'AssignmentGroup': 'Assignment Group',
  'Department': 'Department',
  'Site': 'Site',
  'AssignedRequest': 'Assigned Request',
  'OwnRequest': 'Own Request'
} as const;
export type TransitionPermissionScopeKey = keyof typeof TransitionPermissionScopeKeyToLabel;

export const TransitionPermissionStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive'
} as const;
export type TransitionPermissionStatusKey = keyof typeof TransitionPermissionStatusKeyToLabel;

export interface TransitionPermission {
  /**
   * @displayName Transition Permission ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Permission Code
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  permissionCode: string;
  /**
   * @displayName Scope
   * @validationRule Required for create/update operations
   */
  scopeKey: TransitionPermissionScopeKey;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: TransitionPermissionStatusKey;
  /**
   * @displayName Status Transition ID
   * @validationRule Required for create/update operations
   */
  statusTransitionID: Pick<StatusTransition, 'id' | 'transitionName'>;
  /**
   * @displayName Workspace ID
   * @validationRule Required for create/update operations
   */
  workspaceID: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _TransitionPermission = 'TransitionPermission' as const;