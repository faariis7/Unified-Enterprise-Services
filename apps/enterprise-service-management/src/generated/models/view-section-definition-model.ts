import type { ViewDefinition } from './view-definition-model';

export const ViewSectionDefinitionRendererKeyKeyToLabel = {
  'RequestSummary': 'request_summary',
  'RequestDetails': 'request_details',
  'RequestActivity': 'request_activity',
  'RequestAttachments': 'request_attachments',
  'RequestApprovals': 'request_approvals',
  'RequestServiceTargets': 'request_service_targets'
} as const;
export type ViewSectionDefinitionRendererKeyKey = keyof typeof ViewSectionDefinitionRendererKeyKeyToLabel;

export const ViewSectionDefinitionStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive'
} as const;
export type ViewSectionDefinitionStatusKey = keyof typeof ViewSectionDefinitionStatusKeyToLabel;

export interface ViewSectionDefinition {
  /**
   * @displayName View Section Definition ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Section Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  sectionName: string;
  /**
   * @displayName Renderer Key
   * @validationRule Required for create/update operations
   */
  rendererKeyKey: ViewSectionDefinitionRendererKeyKey;
  /**
   * @displayName Required Permission
   */
  requiredPermission?: string;
  /**
   * @displayName Section Key
   * @validationRule Required for create/update operations
   */
  sectionKey: string;
  /**
   * @displayName Sort Order
   * @validationRule Required for create/update operations
   */
  sortOrder: number;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: ViewSectionDefinitionStatusKey;
  /**
   * @displayName View Definition
   * @validationRule Required for create/update operations
   */
  viewDefinition: Pick<ViewDefinition, 'id' | 'viewName'>;
}

export const _ViewSectionDefinition = 'ViewSectionDefinition' as const;