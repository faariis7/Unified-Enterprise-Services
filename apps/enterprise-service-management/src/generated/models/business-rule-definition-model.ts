import type { BusinessRuleVersion } from './business-rule-version-model';
import type { Person } from './person-model';
import type { Workspace } from './workspace-model';

export const BusinessRuleDefinitionRuleTypeKeyToLabel = {
  'Validation': 'Validation',
  'Eligibility': 'Eligibility',
  'Assignment': 'Assignment',
  'Approval': 'Approval',
  'Workflow': 'Workflow',
  'SLA': 'SLA'
} as const;
export type BusinessRuleDefinitionRuleTypeKey = keyof typeof BusinessRuleDefinitionRuleTypeKeyToLabel;

export const BusinessRuleDefinitionStatusKeyToLabel = {
  'Draft': 'Draft',
  'Published': 'Published',
  'Retired': 'Retired'
} as const;
export type BusinessRuleDefinitionStatusKey = keyof typeof BusinessRuleDefinitionStatusKeyToLabel;

export interface BusinessRuleDefinition {
  /**
   * @displayName Business Rule Definition ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  name1: string;
  /**
   * @displayName Allow Local Overrides
   * @validationRule Required for create/update operations
   */
  allowLocalOverrides: boolean;
  /**
   * @displayName Created At
   * @validationRule Required for create/update operations
   */
  createdAt: string;
  /**
   * @displayName Current Published Version
   */
  currentPublishedVersion?: Pick<BusinessRuleVersion, 'id' | 'snapshotLabel'>;
  /**
   * @displayName Description
   * @validationRule Required for create/update operations
   */
  description: string;
  /**
   * @displayName Is Deleted
   * @validationRule Required for create/update operations
   */
  isDeleted: boolean;
  /**
   * @displayName Owner Person
   */
  ownerPerson?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Rule Type
   * @validationRule Required for create/update operations
   */
  ruleTypeKey: BusinessRuleDefinitionRuleTypeKey;
  /**
   * @displayName Stable Rule Key
   * @validationRule Required for create/update operations
   */
  stableRuleKey: string;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: BusinessRuleDefinitionStatusKey;
  /**
   * @displayName Updated At
   * @validationRule Required for create/update operations
   */
  updatedAt: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _BusinessRuleDefinition = 'BusinessRuleDefinition' as const;