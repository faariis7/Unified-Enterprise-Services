import type { Contract } from './contract-model';
import type { Person } from './person-model';
import type { Workspace } from './workspace-model';

export const ContractObligationRecurrenceKeyToLabel = {
  'None': 'None',
  'Monthly': 'Monthly',
  'Quarterly': 'Quarterly',
  'Semiannual': 'Semiannual',
  'Annual': 'Annual',
  'Custom': 'Custom'
} as const;
export type ContractObligationRecurrenceKey = keyof typeof ContractObligationRecurrenceKeyToLabel;

export const ContractObligationStatusKeyToLabel = {
  'Open': 'Open',
  'InProgress': 'In Progress',
  'Completed': 'Completed',
  'Overdue': 'Overdue',
  'Waived': 'Waived'
} as const;
export type ContractObligationStatusKey = keyof typeof ContractObligationStatusKeyToLabel;

export interface ContractObligation {
  /**
   * @displayName Contract Obligation ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Title
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  title: string;
  /**
   * @displayName Completion Date
   */
  completionDate?: string;
  /**
   * @displayName Completion Notes
   */
  completionNotes?: string;
  /**
   * @displayName Contract
   * @validationRule Required for create/update operations
   */
  contract: Pick<Contract, 'id' | 'title'>;
  /**
   * @displayName Created At
   * @validationRule Required for create/update operations
   */
  createdAt: string;
  /**
   * @displayName Created By
   * @validationRule Required for create/update operations
   */
  createdBy: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Description
   * @validationRule Required for create/update operations
   */
  description: string;
  /**
   * @displayName Due Date
   * @validationRule Required for create/update operations
   */
  dueDate: string;
  /**
   * @displayName Owner Person
   * @validationRule Required for create/update operations
   */
  ownerPerson: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Recurrence
   * @validationRule Required for create/update operations
   */
  recurrenceKey: ContractObligationRecurrenceKey;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: ContractObligationStatusKey;
  /**
   * @displayName Updated At
   * @validationRule Required for create/update operations
   */
  updatedAt: string;
  /**
   * @displayName Updated By
   * @validationRule Required for create/update operations
   */
  updatedBy: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _ContractObligation = 'ContractObligation' as const;