import type { Person } from './person-model';
import type { Request } from './request-model';
import type { Workspace } from './workspace-model';

export const RequestRelationshipRelationshipTypeKeyToLabel = {
  'Related': 'Related',
  'Duplicate': 'Duplicate',
  'Blocks': 'Blocks',
  'BlockedBy': 'Blocked By',
  'Parent': 'Parent',
  'Child': 'Child'
} as const;
export type RequestRelationshipRelationshipTypeKey = keyof typeof RequestRelationshipRelationshipTypeKeyToLabel;

export interface RequestRelationship {
  /**
   * @displayName Request Relationship ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName RelationshipName
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  relationshipName: string;
  /**
   * @displayName CreatedAt
   * @validationRule Required for create/update operations
   */
  createdAt: string;
  /**
   * @displayName CreatedBy
   * @validationRule Required for create/update operations
   */
  createdBy: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName RelatedRequestId
   * @validationRule Required for create/update operations
   */
  relatedRequestId: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName RelationshipType
   * @validationRule Required for create/update operations
   */
  relationshipTypeKey: RequestRelationshipRelationshipTypeKey;
  /**
   * @displayName RequestId
   * @validationRule Required for create/update operations
   */
  requestId: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName WorkspaceId
   * @validationRule Required for create/update operations
   */
  workspaceId: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _RequestRelationship = 'RequestRelationship' as const;