import type { FieldDefinition } from './field-definition-model';
import type { Workspace } from './workspace-model';

export const FieldDependencyDependencyTypeKeyToLabel = {
  'Options': 'Options',
  'Value': 'Value',
  'Visibility': 'Visibility',
  'Requirement': 'Requirement'
} as const;
export type FieldDependencyDependencyTypeKey = keyof typeof FieldDependencyDependencyTypeKeyToLabel;

export const FieldDependencyStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive'
} as const;
export type FieldDependencyStatusKey = keyof typeof FieldDependencyStatusKeyToLabel;

export interface FieldDependency {
  /**
   * @displayName Field Dependency ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Dependency Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  dependencyName: string;
  /**
   * @displayName Dependency Type
   * @validationRule Required for create/update operations
   */
  dependencyTypeKey: FieldDependencyDependencyTypeKey;
  /**
   * @displayName Source Field Definition
   * @validationRule Required for create/update operations
   */
  sourceFieldDefinition: Pick<FieldDefinition, 'id' | 'label'>;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: FieldDependencyStatusKey;
  /**
   * @displayName Target Field Definition
   * @validationRule Required for create/update operations
   */
  targetFieldDefinition: Pick<FieldDefinition, 'id' | 'label'>;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _FieldDependency = 'FieldDependency' as const;