import type { Person } from './person-model';
import type { RequestApproval } from './request-approval-model';
import type { Workspace } from './workspace-model';

export const ApprovalDecisionDecisionKeyToLabel = {
  'Approved': 'Approved',
  'Rejected': 'Rejected',
  'Abstained': 'Abstained',
  'Expired': 'Expired',
  'Escalated': 'Escalated'
} as const;
export type ApprovalDecisionDecisionKey = keyof typeof ApprovalDecisionDecisionKeyToLabel;

export const ApprovalDecisionTargetTypeKeyToLabel = {
  'Request': 'Request',
  'Change': 'Change',
  'Generic': 'Generic'
} as const;
export type ApprovalDecisionTargetTypeKey = keyof typeof ApprovalDecisionTargetTypeKeyToLabel;

export interface ApprovalDecision {
  /**
   * @displayName Approval Decision ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Decision Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  decisionName: string;
  /**
   * @displayName Acting For
   */
  actingFor?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Comments
   */
  comments?: string;
  /**
   * @displayName Decided At
   * @validationRule Required for create/update operations
   */
  decidedAt: string;
  /**
   * @displayName Decided By
   * @validationRule Required for create/update operations
   */
  decidedBy: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Decision
   * @validationRule Required for create/update operations
   */
  decisionKey: ApprovalDecisionDecisionKey;
  /**
   * @displayName Request Approval
   * @validationRule Required for create/update operations
   */
  requestApproval: Pick<RequestApproval, 'id' | 'approvalName'>;
  /**
   * @displayName Source
   * @validationRule Required for create/update operations
   */
  source: string;
  /**
   * @displayName Target Record ID
   * @validationRule Required for create/update operations
   */
  targetRecordID: string;
  /**
   * @displayName Target Type
   * @validationRule Required for create/update operations
   */
  targetTypeKey: ApprovalDecisionTargetTypeKey;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _ApprovalDecision = 'ApprovalDecision' as const;