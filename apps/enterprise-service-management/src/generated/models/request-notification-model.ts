import type { Person } from './person-model';
import type { Request } from './request-model';
import type { Workspace } from './workspace-model';

export const RequestNotificationChannelKeyToLabel = {
  'Email': 'Email',
  'InApp': 'In App',
  'SMS': 'SMS'
} as const;
export type RequestNotificationChannelKey = keyof typeof RequestNotificationChannelKeyToLabel;

export const RequestNotificationStatusKeyToLabel = {
  'Queued': 'Queued',
  'Sent': 'Sent',
  'Failed': 'Failed',
  'Cancelled': 'Cancelled'
} as const;
export type RequestNotificationStatusKey = keyof typeof RequestNotificationStatusKeyToLabel;

export interface RequestNotification {
  /**
   * @displayName Request Notification ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName NotificationName
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  notificationName: string;
  /**
   * @displayName Channel
   * @validationRule Required for create/update operations
   */
  channelKey: RequestNotificationChannelKey;
  /**
   * @displayName Message
   * @validationRule Required for create/update operations
   */
  message: string;
  /**
   * @displayName RecipientPersonId
   * @validationRule Required for create/update operations
   */
  recipientPersonId: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName RequestId
   * @validationRule Required for create/update operations
   */
  requestId: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName SentAt
   * @validationRule Required for create/update operations
   */
  sentAt: string;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: RequestNotificationStatusKey;
  /**
   * @displayName WorkspaceId
   * @validationRule Required for create/update operations
   */
  workspaceId: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _RequestNotification = 'RequestNotification' as const;