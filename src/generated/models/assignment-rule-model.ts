import type { Person } from './person-model';
import type { Workspace } from './workspace-model';

export const AssignmentRulePriorityKeyToLabel = {
  'Low': 'Low',
  'Medium': 'Medium',
  'High': 'High',
  'Critical': 'Critical'
} as const;
export type AssignmentRulePriorityKey = keyof typeof AssignmentRulePriorityKeyToLabel;

export const AssignmentRuleStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive'
} as const;
export type AssignmentRuleStatusKey = keyof typeof AssignmentRuleStatusKeyToLabel;

export const AssignmentRuleTriggerKeyToLabel = {
  'Create': 'Create',
  'Update': 'Update',
  'StatusChange': 'Status Change',
  'Reply': 'Reply',
  'Resolution': 'Resolution'
} as const;
export type AssignmentRuleTriggerKey = keyof typeof AssignmentRuleTriggerKeyToLabel;

export interface AssignmentRule {
  /**
   * @displayName Assignment Rule ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  name1: string;
  /**
   * @displayName Catalog Item Code
   */
  catalogItemCode?: string;
  /**
   * @displayName Department Code
   */
  departmentCode?: string;
  /**
   * @displayName Destination Group Code
   * @validationRule Required for create/update operations
   */
  destinationGroupCode: string;
  /**
   * @displayName Destination Person
   */
  destinationPerson?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Priority
   */
  priorityKey?: AssignmentRulePriorityKey;
  /**
   * @displayName Service Code
   */
  serviceCode?: string;
  /**
   * @displayName Site Code
   */
  siteCode?: string;
  /**
   * @displayName Sort Order
   * @validationRule Required for create/update operations
   */
  sortOrder: number;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: AssignmentRuleStatusKey;
  /**
   * @displayName Stop Processing
   * @validationRule Required for create/update operations
   */
  stopProcessing: boolean;
  /**
   * @displayName Trigger
   * @validationRule Required for create/update operations
   */
  triggerKey: AssignmentRuleTriggerKey;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _AssignmentRule = 'AssignmentRule' as const;