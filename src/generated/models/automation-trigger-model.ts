import type { AutomationRule } from './automation-rule-model';
import type { Workspace } from './workspace-model';

export const AutomationTriggerTriggerTypeKeyToLabel = {
  'RequestCreated': 'Request Created',
  'RequestUpdated': 'Request Updated',
  'StatusChanged': 'Status Changed',
  'AssignmentChanged': 'Assignment Changed',
  'ApprovalCompleted': 'Approval Completed',
  'TargetWarning': 'Target Warning',
  'TargetBreached': 'Target Breached',
  'CommentAdded': 'Comment Added',
  'Scheduled': 'Scheduled'
} as const;
export type AutomationTriggerTriggerTypeKey = keyof typeof AutomationTriggerTriggerTypeKeyToLabel;

export interface AutomationTrigger {
  /**
   * @displayName Automation Trigger ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Trigger Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  triggerName: string;
  /**
   * @displayName Active
   * @validationRule Required for create/update operations
   */
  active: boolean;
  /**
   * @displayName Automation Rule
   * @validationRule Required for create/update operations
   */
  automationRule: Pick<AutomationRule, 'id' | 'name1'>;
  /**
   * @displayName Event Filters
   * @validationRule Required for create/update operations
   */
  eventFilters: string;
  /**
   * @displayName Schedule Expression
   */
  scheduleExpression?: string;
  /**
   * @displayName Trigger Type
   * @validationRule Required for create/update operations
   */
  triggerTypeKey: AutomationTriggerTriggerTypeKey;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _AutomationTrigger = 'AutomationTrigger' as const;