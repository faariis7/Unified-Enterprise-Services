import type { ApprovalStage } from './approval-stage-model';
import type { Person } from './person-model';
import type { Role } from './role-model';
import type { Workspace } from './workspace-model';

export const ApprovalRuleApproverTypeKeyToLabel = {
  'Manager': 'Manager',
  'Person': 'Person',
  'Role': 'Role',
  'Group': 'Group'
} as const;
export type ApprovalRuleApproverTypeKey = keyof typeof ApprovalRuleApproverTypeKeyToLabel;

export const ApprovalRuleRejectionBehaviorKeyToLabel = {
  'StopFlow': 'Stop Flow',
  'ContinueStage': 'Continue Stage'
} as const;
export type ApprovalRuleRejectionBehaviorKey = keyof typeof ApprovalRuleRejectionBehaviorKeyToLabel;

export const ApprovalRuleStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive'
} as const;
export type ApprovalRuleStatusKey = keyof typeof ApprovalRuleStatusKeyToLabel;

export interface ApprovalRule {
  /**
   * @displayName Approval Rule ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Rule Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  ruleName: string;
  /**
   * @displayName Approval Stage
   * @validationRule Required for create/update operations
   */
  approvalStage: Pick<ApprovalStage, 'id' | 'name1'>;
  /**
   * @displayName Approver Type
   * @validationRule Required for create/update operations
   */
  approverTypeKey: ApprovalRuleApproverTypeKey;
  /**
   * @displayName Condition Expression
   */
  conditionExpression?: string;
  /**
   * @displayName Delegation Allowed
   * @validationRule Required for create/update operations
   */
  delegationAllowed: boolean;
  /**
   * @displayName Escalation Group Code
   */
  escalationGroupCode?: string;
  /**
   * @displayName Group Code
   */
  groupCode?: string;
  /**
   * @displayName Minimum Approvals
   * @validationRule Required for create/update operations
   */
  minimumApprovals: number;
  /**
   * @displayName Person
   */
  person?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Rejection Behavior
   * @validationRule Required for create/update operations
   */
  rejectionBehaviorKey: ApprovalRuleRejectionBehaviorKey;
  /**
   * @displayName Role
   */
  role?: Pick<Role, 'id' | 'roleName'>;
  /**
   * @displayName Rule Order
   * @validationRule Required for create/update operations
   */
  ruleOrder: number;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: ApprovalRuleStatusKey;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _ApprovalRule = 'ApprovalRule' as const;