import type { ApprovalDefinition } from './approval-definition-model';
import type { AutomationRule } from './automation-rule-model';
import type { Workspace } from './workspace-model';

export const AutomationActionActionTypeKeyToLabel = {
  'Assign': 'Assign',
  'UpdateField': 'Update Field',
  'ChangeStatus': 'Change Status',
  'CreateTask': 'Create Task',
  'StartApproval': 'Start Approval',
  'SendNotification': 'Send Notification',
  'AddComment': 'Add Comment',
  'CallWebhook': 'Call Webhook',
  'SetTarget': 'Set Target',
  'Escalate': 'Escalate'
} as const;
export type AutomationActionActionTypeKey = keyof typeof AutomationActionActionTypeKeyToLabel;

export const AutomationActionStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive'
} as const;
export type AutomationActionStatusKey = keyof typeof AutomationActionStatusKeyToLabel;

export interface AutomationAction {
  /**
   * @displayName Automation Action ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Action Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  actionName: string;
  /**
   * @displayName Action Type
   * @validationRule Required for create/update operations
   */
  actionTypeKey: AutomationActionActionTypeKey;
  /**
   * @displayName Approval Definition
   */
  approvalDefinition?: Pick<ApprovalDefinition, 'id' | 'name1'>;
  /**
   * @displayName Automation Rule
   * @validationRule Required for create/update operations
   */
  automationRule: Pick<AutomationRule, 'id' | 'name1'>;
  /**
   * @displayName Configured Value
   */
  configuredValue?: string;
  /**
   * @displayName Notification Message
   */
  notificationMessage?: string;
  /**
   * @displayName Sort Order
   * @validationRule Required for create/update operations
   */
  sortOrder: number;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: AutomationActionStatusKey;
  /**
   * @displayName Target Field
   */
  targetField?: string;
  /**
   * @displayName Task Title
   */
  taskTitle?: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _AutomationAction = 'AutomationAction' as const;