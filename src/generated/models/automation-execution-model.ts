import type { Person } from './person-model';
import type { AutomationRule } from './automation-rule-model';
import type { Request } from './request-model';
import type { Workspace } from './workspace-model';

export const AutomationExecutionStatusKeyToLabel = {
  'Running': 'Running',
  'Succeeded': 'Succeeded',
  'Failed': 'Failed',
  'Skipped': 'Skipped',
  'Blocked': 'Blocked'
} as const;
export type AutomationExecutionStatusKey = keyof typeof AutomationExecutionStatusKeyToLabel;

export const AutomationExecutionTriggerKeyToLabel = {
  'Create': 'Create',
  'Update': 'Update',
  'StatusChange': 'Status Change',
  'Assignment': 'Assignment',
  'Approval': 'Approval',
  'TargetWarning': 'Target Warning',
  'TargetBreach': 'Target Breach',
  'Reply': 'Reply',
  'Resolution': 'Resolution',
  'Schedule': 'Schedule'
} as const;
export type AutomationExecutionTriggerKey = keyof typeof AutomationExecutionTriggerKeyToLabel;

export interface AutomationExecution {
  /**
   * @displayName Automation Execution ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Correlation Key
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  correlationKey: string;
  /**
   * @displayName Actor Person
   * @validationRule Required for create/update operations
   */
  actorPerson: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Automation Rule
   */
  automationRule?: Pick<AutomationRule, 'id' | 'name1'>;
  /**
   * @displayName Completed At
   * @validationRule Required for create/update operations
   */
  completedAt: string;
  /**
   * @displayName Depth
   * @validationRule Required for create/update operations
   */
  depth: number;
  /**
   * @displayName Failure Code
   */
  failureCode?: string;
  /**
   * @displayName Failure Message
   */
  failureMessage?: string;
  /**
   * @displayName Request
   * @validationRule Required for create/update operations
   */
  request: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName Source
   * @validationRule Required for create/update operations
   */
  source: string;
  /**
   * @displayName Started At
   * @validationRule Required for create/update operations
   */
  startedAt: string;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: AutomationExecutionStatusKey;
  /**
   * @displayName Trigger
   * @validationRule Required for create/update operations
   */
  triggerKey: AutomationExecutionTriggerKey;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _AutomationExecution = 'AutomationExecution' as const;