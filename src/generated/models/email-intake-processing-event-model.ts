import type { Person } from './person-model';
import type { EmailIntakeMessage } from './email-intake-message-model';

export const EmailIntakeProcessingEventEventTypeKeyToLabel = {
  'Discovered': 'Discovered',
  'Validation': 'Validation',
  'Matched': 'Matched',
  'RequestCreated': 'RequestCreated',
  'ReplyAdded': 'ReplyAdded',
  'AttachmentAdded': 'AttachmentAdded',
  'Duplicate': 'Duplicate',
  'NeedsReview': 'NeedsReview',
  'Failed': 'Failed',
  'Retried': 'Retried'
} as const;
export type EmailIntakeProcessingEventEventTypeKey = keyof typeof EmailIntakeProcessingEventEventTypeKeyToLabel;

export interface EmailIntakeProcessingEvent {
  /**
   * @displayName Email Intake Processing Event ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Event Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  eventName: string;
  /**
   * @displayName Actor Person
   */
  actorPerson?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Detail
   * @validationRule Required for create/update operations
   */
  detail: string;
  /**
   * @displayName Email Intake Message
   * @validationRule Required for create/update operations
   */
  emailIntakeMessage: Pick<EmailIntakeMessage, 'id' | 'messageName'>;
  /**
   * @displayName Event Type
   * @validationRule Required for create/update operations
   */
  eventTypeKey: EmailIntakeProcessingEventEventTypeKey;
  /**
   * @displayName Occurred At
   * @validationRule Required for create/update operations
   */
  occurredAt: string;
}

