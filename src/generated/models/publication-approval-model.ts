import type { FormVersion } from './form-version-model';
import type { Person } from './person-model';
import type { Service } from './service-model';
import type { Workspace } from './workspace-model';

export const PublicationApprovalStatusKeyToLabel = {
  'Pending': 'Pending',
  'Approved': 'Approved',
  'Rejected': 'Rejected',
  'Withdrawn': 'Withdrawn'
} as const;
export type PublicationApprovalStatusKey = keyof typeof PublicationApprovalStatusKeyToLabel;

export interface PublicationApproval {
  /**
   * @displayName Publication Approval ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Approval Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  approvalName: string;
  /**
   * @displayName Change Reason
   * @validationRule Required for create/update operations
   */
  changeReason: string;
  /**
   * @displayName Form Version
   * @validationRule Required for create/update operations
   */
  formVersion: Pick<FormVersion, 'id' | 'snapshotLabel'>;
  /**
   * @displayName Is Deleted
   * @validationRule Required for create/update operations
   */
  isDeleted: boolean;
  /**
   * @displayName Maker Checker Satisfied
   * @validationRule Required for create/update operations
   */
  makerCheckerSatisfied: boolean;
  /**
   * @displayName Requested At
   * @validationRule Required for create/update operations
   */
  requestedAt: string;
  /**
   * @displayName Requested By
   * @validationRule Required for create/update operations
   */
  requestedBy: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Review Comment
   */
  reviewComment?: string;
  /**
   * @displayName Review Date
   * @validationRule Required for create/update operations
   */
  reviewDate: string;
  /**
   * @displayName Reviewed At
   */
  reviewedAt?: string;
  /**
   * @displayName Reviewed By
   */
  reviewedBy?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Service
   * @validationRule Required for create/update operations
   */
  service: Pick<Service, 'id' | 'serviceName'>;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: PublicationApprovalStatusKey;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _PublicationApproval = 'PublicationApproval' as const;