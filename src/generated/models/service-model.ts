import type { FormVersion } from './form-version-model';
import type { Person } from './person-model';
import type { ServiceCategory } from './service-category-model';
import type { Workspace } from './workspace-model';

export const ServiceLifecycleStateKeyToLabel = {
  'Draft': 'Draft',
  'Published': 'Published',
  'Retired': 'Retired'
} as const;
export type ServiceLifecycleStateKey = keyof typeof ServiceLifecycleStateKeyToLabel;

export const ServiceStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive'
} as const;
export type ServiceStatusKey = keyof typeof ServiceStatusKeyToLabel;

export interface Service {
  /**
   * @displayName Service ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Service Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  serviceName: string;
  /**
   * @displayName Audience Configuration
   */
  audienceConfiguration?: string;
  /**
   * @displayName Availability Configuration
   */
  availabilityConfiguration?: string;
  /**
   * @displayName Created At
   */
  createdAt?: string;
  /**
   * @displayName Current Published Form Version
   */
  currentPublishedFormVersion?: Pick<FormVersion, 'id' | 'snapshotLabel'>;
  /**
   * @displayName Default Assignment Group Code
   * @validationRule Required for create/update operations
   */
  defaultAssignmentGroupCode: string;
  /**
   * @displayName Description
   * @validationRule Required for create/update operations
   */
  description: string;
  /**
   * @displayName Instructions
   */
  instructions?: string;
  /**
   * @displayName Is Deleted
   */
  isDeleted?: boolean;
  /**
   * @displayName Lifecycle State
   */
  lifecycleStateKey?: ServiceLifecycleStateKey;
  /**
   * @displayName Owner
   */
  owner?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Owner Person
   */
  ownerPerson?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Reporting Configuration
   */
  reportingConfiguration?: string;
  /**
   * @displayName Requester Eligible
   * @validationRule Required for create/update operations
   */
  requesterEligible: boolean;
  /**
   * @displayName Service Category
   * @validationRule Required for create/update operations
   */
  serviceCategory: Pick<ServiceCategory, 'id' | 'name1'>;
  /**
   * @displayName Service Code
   * @validationRule Required for create/update operations
   */
  serviceCode: string;
  /**
   * @displayName Sort Order
   */
  sortOrder?: number;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: ServiceStatusKey;
  /**
   * @displayName Updated At
   */
  updatedAt?: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _Service = 'Service' as const;