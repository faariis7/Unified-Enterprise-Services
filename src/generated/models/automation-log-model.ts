import type { AutomationExecution } from './automation-execution-model';
import type { AutomationRule } from './automation-rule-model';
import type { AutomationTrigger } from './automation-trigger-model';
import type { Request } from './request-model';
import type { Workspace } from './workspace-model';

export const AutomationLogOutcomeKeyToLabel = {
  'Succeeded': 'Succeeded',
  'Skipped': 'Skipped',
  'Blocked': 'Blocked',
  'Failed': 'Failed'
} as const;
export type AutomationLogOutcomeKey = keyof typeof AutomationLogOutcomeKeyToLabel;

export interface AutomationLog {
  /**
   * @displayName Automation Log ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Log Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  logName: string;
  /**
   * @displayName Action Summary
   * @validationRule Required for create/update operations
   */
  actionSummary: string;
  /**
   * @displayName Automation Execution
   * @validationRule Required for create/update operations
   */
  automationExecution: Pick<AutomationExecution, 'id' | 'correlationKey'>;
  /**
   * @displayName Automation Rule
   * @validationRule Required for create/update operations
   */
  automationRule: Pick<AutomationRule, 'id' | 'name1'>;
  /**
   * @displayName Automation Trigger
   * @validationRule Required for create/update operations
   */
  automationTrigger: Pick<AutomationTrigger, 'id' | 'triggerName'>;
  /**
   * @displayName Completed At
   * @validationRule Required for create/update operations
   */
  completedAt: string;
  /**
   * @displayName Condition Summary
   * @validationRule Required for create/update operations
   */
  conditionSummary: string;
  /**
   * @displayName Correlation Key
   * @validationRule Required for create/update operations
   */
  correlationKey: string;
  /**
   * @displayName Depth
   * @validationRule Required for create/update operations
   */
  depth: number;
  /**
   * @displayName Loop Prevention Reason
   */
  loopPreventionReason?: string;
  /**
   * @displayName Outcome
   * @validationRule Required for create/update operations
   */
  outcomeKey: AutomationLogOutcomeKey;
  /**
   * @displayName Request
   * @validationRule Required for create/update operations
   */
  request: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName Started At
   * @validationRule Required for create/update operations
   */
  startedAt: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _AutomationLog = 'AutomationLog' as const;