import type { EmailIntakeConfiguration } from './email-intake-configuration-model';
import type { Person } from './person-model';
import type { Request } from './request-model';
import type { Workspace } from './workspace-model';

export const EmailIntakeMessageProcessingStatusKeyToLabel = {
  'Discovered': 'Discovered',
  'Processing': 'Processing',
  'Processed': 'Processed',
  'Duplicate': 'Duplicate',
  'NeedsReview': 'NeedsReview',
  'Failed': 'Failed'
} as const;
export type EmailIntakeMessageProcessingStatusKey = keyof typeof EmailIntakeMessageProcessingStatusKeyToLabel;

export interface EmailIntakeMessage {
  /**
   * @displayName Email Intake Message ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Message Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  messageName: string;
  /**
   * @displayName Attempt Count
   * @validationRule Required for create/update operations
   */
  attemptCount: number;
  /**
   * @displayName Body Preview
   * @validationRule Required for create/update operations
   */
  bodyPreview: string;
  /**
   * @displayName Conversation ID
   * @validationRule Required for create/update operations
   */
  conversationID: string;
  /**
   * @displayName Email Intake Configuration
   * @validationRule Required for create/update operations
   */
  emailIntakeConfiguration: Pick<EmailIntakeConfiguration, 'id' | 'configurationName'>;
  /**
   * @displayName Has Attachments
   * @validationRule Required for create/update operations
   */
  hasAttachments: boolean;
  /**
   * @displayName Internet Message ID
   * @validationRule Required for create/update operations
   */
  internetMessageID: string;
  /**
   * @displayName Last Error
   */
  lastError?: string;
  /**
   * @displayName Matched Person
   */
  matchedPerson?: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Matched Request
   */
  matchedRequest?: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName Microsoft Message ID
   * @validationRule Required for create/update operations
   */
  microsoftMessageID: string;
  /**
   * @displayName Outcome Detail
   * @validationRule Required for create/update operations
   */
  outcomeDetail: string;
  /**
   * @displayName Processed At
   * @validationRule Required for create/update operations
   */
  processedAt: string;
  /**
   * @displayName Processing Status
   * @validationRule Required for create/update operations
   */
  processingStatusKey: EmailIntakeMessageProcessingStatusKey;
  /**
   * @displayName Received At
   * @validationRule Required for create/update operations
   */
  receivedAt: string;
  /**
   * @displayName Sender Email
   * @validationRule Required for create/update operations
   */
  senderEmail: string;
  /**
   * @displayName Sender Name
   * @validationRule Required for create/update operations
   */
  senderName: string;
  /**
   * @displayName Subject
   * @validationRule Required for create/update operations
   */
  subject: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _EmailIntakeMessage = 'EmailIntakeMessage' as const;