import type { FieldDefinition } from './field-definition-model';
import type { Workspace } from './workspace-model';

export const FieldVisibilityRuleEffectKeyToLabel = {
  'Show': 'Show',
  'Hide': 'Hide',
  'Require': 'Require',
  'ReadOnly': 'Read only'
} as const;
export type FieldVisibilityRuleEffectKey = keyof typeof FieldVisibilityRuleEffectKeyToLabel;

export const FieldVisibilityRuleOperatorKeyToLabel = {
  'Equals': 'Equals',
  'NotEquals': 'Not equals',
  'Contains': 'Contains',
  'IsEmpty': 'Is empty',
  'IsNotEmpty': 'Is not empty'
} as const;
export type FieldVisibilityRuleOperatorKey = keyof typeof FieldVisibilityRuleOperatorKeyToLabel;

export const FieldVisibilityRuleStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive'
} as const;
export type FieldVisibilityRuleStatusKey = keyof typeof FieldVisibilityRuleStatusKeyToLabel;

export interface FieldVisibilityRule {
  /**
   * @displayName Field Visibility Rule ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Rule Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  ruleName: string;
  /**
   * @displayName Comparison Value
   */
  comparisonValue?: string;
  /**
   * @displayName Created At
   */
  createdAt?: string;
  /**
   * @displayName Dependent Field Definition
   */
  dependentFieldDefinition?: Pick<FieldDefinition, 'id' | 'label'>;
  /**
   * @displayName Effect
   * @validationRule Required for create/update operations
   */
  effectKey: FieldVisibilityRuleEffectKey;
  /**
   * @displayName Field Definition
   * @validationRule Required for create/update operations
   */
  fieldDefinition: Pick<FieldDefinition, 'id' | 'label'>;
  /**
   * @displayName Is Deleted
   */
  isDeleted?: boolean;
  /**
   * @displayName Operator
   * @validationRule Required for create/update operations
   */
  operatorKey: FieldVisibilityRuleOperatorKey;
  /**
   * @displayName Sort Order
   */
  sortOrder?: number;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: FieldVisibilityRuleStatusKey;
  /**
   * @displayName Updated At
   */
  updatedAt?: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _FieldVisibilityRule = 'FieldVisibilityRule' as const;