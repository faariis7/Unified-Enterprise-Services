import type { Person } from './person-model';
import type { Request } from './request-model';
import type { Workspace } from './workspace-model';

export const RequestActivityActivityTypeKeyToLabel = {
  'Comment': 'Comment',
  'Assignment': 'Assignment',
  'StatusChange': 'Status Change',
  'CustomerCommunication': 'Customer Communication',
  'InternalNote': 'Internal Note',
  'Resolution': 'Resolution'
} as const;
export type RequestActivityActivityTypeKey = keyof typeof RequestActivityActivityTypeKeyToLabel;

export interface RequestActivity {
  /**
   * @displayName Request Activity ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Request Activity Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  requestActivityName: string;
  /**
   * @displayName Activity Type
   * @validationRule Required for create/update operations
   */
  activityTypeKey: RequestActivityActivityTypeKey;
  /**
   * @displayName Actor
   * @validationRule Required for create/update operations
   */
  actor: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Body
   * @validationRule Required for create/update operations
   */
  body: string;
  /**
   * @displayName Occurred At
   * @validationRule Required for create/update operations
   */
  occurredAt: string;
  /**
   * @displayName Request
   * @validationRule Required for create/update operations
   */
  request: Pick<Request, 'id' | 'requestNumber'>;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _RequestActivity = 'RequestActivity' as const;