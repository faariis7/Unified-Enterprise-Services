import type { Person } from './person-model';
import type { Contract } from './contract-model';
import type { Workspace } from './workspace-model';

export const ContractActivityActivityTypeKeyToLabel = {
  'Created': 'Created',
  'Updated': 'Updated',
  'StatusChanged': 'Status Changed',
  'RenewalAction': 'Renewal Action',
  'ObligationAction': 'Obligation Action',
  'DocumentAction': 'Document Action'
} as const;
export type ContractActivityActivityTypeKey = keyof typeof ContractActivityActivityTypeKeyToLabel;

export interface ContractActivity {
  /**
   * @displayName Contract Activity ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Summary
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  summary: string;
  /**
   * @displayName Activity Type
   * @validationRule Required for create/update operations
   */
  activityTypeKey: ContractActivityActivityTypeKey;
  /**
   * @displayName Actor Person
   * @validationRule Required for create/update operations
   */
  actorPerson: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Contract
   * @validationRule Required for create/update operations
   */
  contract: Pick<Contract, 'id' | 'title'>;
  /**
   * @displayName Details
   * @validationRule Required for create/update operations
   */
  details: string;
  /**
   * @displayName Field Name
   */
  fieldName?: string;
  /**
   * @displayName New Value
   */
  newValue?: string;
  /**
   * @displayName Occurred At
   * @validationRule Required for create/update operations
   */
  occurredAt: string;
  /**
   * @displayName Previous Value
   */
  previousValue?: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _ContractActivity = 'ContractActivity' as const;