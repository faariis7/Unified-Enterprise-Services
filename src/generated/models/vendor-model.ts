import type { Person } from './person-model';
import type { Workspace } from './workspace-model';

export const VendorRiskRatingKeyToLabel = {
  'Low': 'Low',
  'Medium': 'Medium',
  'High': 'High',
  'Critical': 'Critical'
} as const;
export type VendorRiskRatingKey = keyof typeof VendorRiskRatingKeyToLabel;

export const VendorStatusKeyToLabel = {
  'Active': 'Active',
  'Inactive': 'Inactive',
  'Suspended': 'Suspended'
} as const;
export type VendorStatusKey = keyof typeof VendorStatusKeyToLabel;

export interface Vendor {
  /**
   * @displayName Vendor ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Vendor Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  vendorName: string;
  /**
   * @displayName Category
   * @validationRule Required for create/update operations
   */
  category: string;
  /**
   * @displayName Created At
   * @validationRule Required for create/update operations
   */
  createdAt: string;
  /**
   * @displayName Created By
   * @validationRule Required for create/update operations
   */
  createdBy: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Primary Contact Email
   * @validationRule Required for create/update operations
   */
  primaryContactEmail: string;
  /**
   * @displayName Primary Contact Name
   * @validationRule Required for create/update operations
   */
  primaryContactName: string;
  /**
   * @displayName Primary Contact Phone
   * @validationRule Required for create/update operations
   */
  primaryContactPhone: string;
  /**
   * @displayName Registration and Tax Reference
   * @validationRule Required for create/update operations
   */
  registrationAndTaxReference: string;
  /**
   * @displayName Risk Rating
   * @validationRule Required for create/update operations
   */
  riskRatingKey: VendorRiskRatingKey;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: VendorStatusKey;
  /**
   * @displayName Updated At
   * @validationRule Required for create/update operations
   */
  updatedAt: string;
  /**
   * @displayName Updated By
   * @validationRule Required for create/update operations
   */
  updatedBy: Pick<Person, 'id' | 'displayName'>;
  /**
   * @displayName Vendor Code
   * @validationRule Required for create/update operations
   */
  vendorCode: string;
  /**
   * @displayName Workspace
   * @validationRule Required for create/update operations
   */
  workspace: Pick<Workspace, 'id' | 'workspaceName'>;
}

export const _Vendor = 'Vendor' as const;